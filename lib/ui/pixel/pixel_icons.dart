/// Отрисовка одного глифа.
class PixelIcon extends StatelessWidget {
  const PixelIcon(
    this.name, {
    super.key,
    this.size = 20,
    required this.color,
    this.secondary,
  });

  /// Имя глифа из [PixelGlyphs.all] либо `'mark'` — крупный знак приложения.
  final String name;
  final double size;
  final Color color;
  final Color? secondary;

  @override
  Widget build(BuildContext context) {
    final glyph = name == 'mark'
        ? PixelGlyphs.mark
        : PixelGlyphs.all[name];
    assert(glyph != null, 'Неизвестный пиксельный глиф: $name');
    return SizedBox(
      width: size,
      height: size,
      // Иконки статичны, но часто живут внутри анимированных родителей
      // (карточка проседает в тень, кнопка отправки вспыхивает). Без
      // границы перерисовки сетка перерисовывалась бы на каждом кадре
      // такой анимации.
      child: RepaintBoundary(
        child: CustomPaint(
          painter: _GlyphPainter(
            glyph ?? const ['#'],
            color,
            // 'o' — светлая вставка внутри залитого силуэта (белая сеть в
            // знаке приложения). Приглушённый вариант основного цвета тут
            // читался бы как грязь, а не как деталь.
            secondary ?? Colors.white,
          ),
        ),
      ),
    );
  }
}

class _GlyphPainter extends CustomPainter {
  const _GlyphPainter(this.glyph, this.color, this.secondary);

  final List<String> glyph;
  final Color color;
  final Color secondary;

  @override
  void paint(Canvas canvas, Size size) {
    if (glyph.isEmpty) return;
    final cols = glyph.first.length;
    final cell = size.width / cols;

    final main = Paint()..color = color;
    final alt = Paint()..color = secondary;

    for (var y = 0; y < glyph.length; y++) {
      final row = glyph[y];
      for (var x = 0; x < row.length; x++) {
        final ch = row.codeUnitAt(x);
        if (ch == 0x2E) continue; // '.'
        // Ячейки рисуются с нахлёстом в полпикселя. Раньше между ними
        // оставался зазор в пиксель — на глаз это давало рваный контур и
        // было главной причиной, по которой набор выглядел небрежным.
        canvas.drawRect(
          Rect.fromLTWH(x * cell, y * cell, cell + 0.5, cell + 0.5),
          ch == 0x6F ? alt : main, // 'o'
        );
      }
    }
  }

  @override
  bool shouldRepaint(_GlyphPainter old) =>
      old.glyph != glyph || old.color != color || old.secondary != secondary;
}

/// Кнопка-иконка с пиксельным глифом.
class PixelIconButton extends StatelessWidget {
  const PixelIconButton({
    super.key,
    required this.icon,
    required this.onPressed,
    this.size = 20,
    this.color,
    this.tooltip,
  });

  final String icon;
  final VoidCallback? onPressed;
  final double size;
  final Color? color;
  final String? tooltip;

  @override
  Widget build(BuildContext context) {
    final colors = context.colors;
    final c = color ?? colors.textPrimary;
    final button = GestureDetector(
      onTap: onPressed == null
          ? null
          : () {
              Haptics.tap();
              onPressed!();
            },
      behavior: HitTestBehavior.opaque,
      child: Padding(
        // 44x44 минимальная зона нажатия при иконке 20px.
        padding: const EdgeInsets.all(12),
        child: PixelIcon(
          icon,
          size: size,
          color: onPressed == null ? colors.textTertiary : c,
        ),
      ),
    );
    return tooltip == null ? button : Tooltip(message: tooltip!, child: button);
  }
}

/// Глиф для файла по его имени.
///
/// Мелкая, но заметная деталь: у типа файла, который приложение узнаёт,
/// вместо безликого листа появляется своя иконка. Картинки, звук и видео
/// сюда не попадают — у них свой [ItemKind] и превью.
String fileGlyphFor(String? fileName) {
  final name = (fileName ?? '').toLowerCase();
  final ext = name.contains('.') ? name.split('.').last : '';
  const archive = {'zip', 'rar', '7z', 'tar', 'gz', 'xz', 'zst', 'apk', 'iso'};
  const document = {'pdf', 'doc', 'docx', 'odt', 'rtf', 'epub', 'djvu'};
  const code = {
    'dart', 'py', 'js', 'ts', 'json', 'yaml', 'yml', 'sh', 'c', 'h', 'cpp',
    'rs', 'go', 'java', 'kt', 'xml', 'html', 'css', 'toml', 'ini', 'conf',
  };
  if (archive.contains(ext)) return 'archive';
  if (document.contains(ext)) return 'pdf';
  if (code.contains(ext)) return 'code';
  if (ext == 'txt' || ext == 'md' || ext == 'log') return 'text';
  return 'file';
}
