/// Отрисовка одного глифа.
///
/// Ячейки кладутся по целым числам, а размер округляется вниз до кратного
/// сетке — иначе на дробном devicePixelRatio соседние ячейки получают
/// разную ширину и «пиксель» перестаёт быть квадратным.
class PixelIcon extends StatelessWidget {
  final String name;
  final double size;
  final Color color;
  final Color? secondary;

  const PixelIcon(
    this.name, {
    super.key,
    this.size = 20,
    required this.color,
    this.secondary,
  });

  @override
  Widget build(BuildContext context) {
    final glyph = PixelGlyphs.all[name];
    assert(glyph != null, 'Неизвестный пиксельный глиф: $name');
    return SizedBox(
      width: size,
      height: size,
      child: CustomPaint(
        painter: _GlyphPainter(
          glyph ?? const ['#'],
          color,
          // 'o' — светлая вставка внутри залитого силуэта (сейчас это
          // белая сеть внутри знака приложения). Приглушённый вариант
          // основного цвета тут не годится: на синем корпусе он читается
          // как грязь, а не как деталь.
          secondary ?? Colors.white,
        ),
      ),
    );
  }
}

class _GlyphPainter extends CustomPainter {
  final List<String> glyph;
  final Color color;
  final Color secondary;

  _GlyphPainter(this.glyph, this.color, this.secondary);

  @override
  void paint(Canvas canvas, Size size) {
    final rows = glyph.length;
    final cols = glyph.first.length;
    // Одна ячейка — целое число логических пикселей, но не меньше 1:
    // при size < сетки глиф всё равно должен нарисоваться, пусть и грубо.
    final cell = (size.width / cols).floorToDouble().clamp(1.0, double.infinity);
    final w = cell * cols;
    final h = cell * rows;
    // Центрируем остаток, чтобы глиф не липнул к левому верхнему углу.
    final dx = ((size.width - w) / 2).floorToDouble();
    final dy = ((size.height - h) / 2).floorToDouble();

    final main = Paint()..color = color;
    final alt = Paint()..color = secondary;

    for (var r = 0; r < rows; r++) {
      final line = glyph[r];
      for (var c = 0; c < cols && c < line.length; c++) {
        final ch = line.codeUnitAt(c);
        if (ch == 0x2E) continue; // '.'
        canvas.drawRect(
          Rect.fromLTWH(dx + c * cell, dy + r * cell, cell, cell),
          ch == 0x6F ? alt : main, // 'o' — вторичный цвет
        );
      }
    }
  }

  @override
  bool shouldRepaint(_GlyphPainter old) =>
      old.glyph != glyph || old.color != color || old.secondary != secondary;
}

/// Кнопка-иконка с пиксельным глифом и тактильным откликом.
class PixelIconButton extends StatelessWidget {
  final String icon;
  final VoidCallback? onPressed;
  final double size;
  final Color? color;
  final String? tooltip;

  const PixelIconButton({
    super.key,
    required this.icon,
    required this.onPressed,
    this.size = 20,
    this.color,
    this.tooltip,
  });

  @override
  Widget build(BuildContext context) {
    final c = color ?? context.colors.textPrimary;
    final button = GestureDetector(
      onTap: onPressed,
      behavior: HitTestBehavior.opaque,
      child: Padding(
        // 44x44 минимальная зона нажатия при иконке 20px.
        padding: const EdgeInsets.all(12),
        child: PixelIcon(
          icon,
          size: size,
          color: onPressed == null ? c.withValues(alpha: 0.3) : c,
        ),
      ),
    );
    return tooltip == null ? button : Tooltip(message: tooltip!, child: button);
  }
}
