/// Виджет пиксельной иконки: рисует сетку глифа квадратами, без сглаживания.
class PixelIcon extends StatelessWidget {
  final String name;
  final double size;
  final Color? color;

  const PixelIcon(this.name, {super.key, this.size = 20, this.color});

  @override
  Widget build(BuildContext context) {
    final glyph = PixelIcons.byName(name);
    final cs = Theme.of(context).colorScheme;
    final c = color ?? cs.onSurface;
    if (glyph == null) {
      // Не должно происходить в норме — заметный маркер вместо тихого краша.
      return Icon(Icons.crop_square_rounded, size: size, color: c);
    }
    return SizedBox(
      width: size,
      height: size,
      child: CustomPaint(painter: _PixelIconPainter(glyph.rows, c)),
    );
  }
}

class _PixelIconPainter extends CustomPainter {
  final List<String> rows;
  final Color color;
  _PixelIconPainter(this.rows, this.color);

  @override
  void paint(Canvas canvas, Size size) {
    final cell = size.width / _kGrid;
    final paint = Paint()..color = color;
    for (var r = 0; r < _kGrid; r++) {
      final row = r < rows.length ? rows[r] : '';
      for (var c = 0; c < _kGrid; c++) {
        final ch = c < row.length ? row[c] : '.';
        if (ch == '#') {
          canvas.drawRect(
            Rect.fromLTWH(c * cell, r * cell, cell + 0.5, cell + 0.5),
            paint,
          );
        }
      }
    }
  }

  @override
  bool shouldRepaint(covariant _PixelIconPainter old) =>
      old.rows != rows || old.color != color;
}
