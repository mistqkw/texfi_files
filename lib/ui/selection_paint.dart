/// Применяет «закраску» выделения к отрезку строк.
///
/// Вынесено из экрана отдельной функцией, потому что именно здесь была
/// ошибка: раньше отмечалась только строка прямо под пальцем. События
/// движения приходят раз в кадр, и при быстрой протяжке между двумя
/// замерами оставалось несколько строк — они молча не попадали в
/// выделение, и потом «в папку добавилось не всё, что выделил».
///
/// [from] и [to] — индексы предыдущего и текущего замера; порядок не важен,
/// отрезок берётся включительно в обе стороны. Индексы за пределами списка
/// игнорируются: лента могла измениться между замерами.
///
/// Возвращает true, если набор действительно изменился — вызывающему это
/// нужно, чтобы не дёргать перерисовку и вибро на каждое движение пальца
/// внутри одной строки.
bool applySelectionPaint({
  required Set<String> selected,
  required List<String> ids,
  required int from,
  required int to,
  required bool value,
}) {
  var lo = from <= to ? from : to;
  var hi = from <= to ? to : from;
  if (hi < 0 || lo >= ids.length) return false;
  if (lo < 0) lo = 0;
  if (hi >= ids.length) hi = ids.length - 1;

  var changed = false;
  for (var i = lo; i <= hi; i++) {
    changed |= value ? selected.add(ids[i]) : selected.remove(ids[i]);
  }
  return changed;
}
